  if(is.prior.factor(prior_variable)){

    samples <- .as_mixed_priors.factor(prior_variable, parameter, seed, n_samples)

  }else if(is.prior.simple(prior_variable)){

    samples <- .as_mixed_priors.simple(prior_variable, parameter, seed, n_samples)

  }

  # merge with names and attributes
  samples       <- samples * inclusion

  class(samples) <- c(class(samples), "mixed_posteriors.spike_and_slab")
  attr(samples, "sample_ind") <- FALSE
  attr(samples, "models_ind") <- inclusion
  attr(samples, "prior_list") <- prior
  if(!is.null(dim(samples))){
    samples <- .posterior_support_set_columns_from_prior_list(samples, prior)
  }else{
    samples <- .posterior_support_set_from_prior_list(samples, prior)
  }

  return(samples)
}
.as_mixed_priors.mixture        <- function(prior, parameter, seed = NULL, n_samples = 10000){

  # check input
  check_list(prior, "prior")
  check_char(parameter, "parameter")
  check_real(seed, "seed", allow_NULL = TRUE)
  check_int(n_samples, "n_samples")

  is_PET            <- sapply(prior, is.prior.PET)
  is_PEESE          <- sapply(prior, is.prior.PEESE)
  is_weightfunction <- sapply(prior, is.prior.weightfunction)
  is_phacking       <- sapply(prior, is_prior_phacking)
  is_bias           <- sapply(prior, is_prior_bias)

  if(any(is_PET | is_PEESE | is_weightfunction | is_phacking | is_bias)){

    temp_samples <- .mix_priors.bias(prior, parameter = parameter, seed = seed, n_samples = n_samples)

  }else{

    is_simple <- sapply(prior, is.prior.simple)
    is_factor <- sapply(prior, is.prior.factor)

    if(any(is_factor)){
      temp_samples <- .mix_priors.factor(prior, parameter = parameter, seed = seed, n_samples = n_samples)
    }else{
      temp_samples <- .mix_priors.simple(prior, parameter = parameter, seed = seed, n_samples = n_samples)
    }

  }

  # the samples parameters need to be randomly shuffled
  # (the  .mix_priors.XXX functions generate the samples model by model to keep bridge-sampling model-averaging consistent structure,
  #  this however does not apply to the spike an slab priors)
  random_ind <- sample(n_samples)
  if(is.null(dim(temp_samples))){
    samples <- temp_samples[random_ind]
  }else{
    samples <- temp_samples[random_ind,,drop=FALSE]
  }
  attributes(samples) <- attributes(temp_samples)
  attr(samples, "sample_ind") <- FALSE
  attr(samples, "models_ind") <- attr(samples, "models_ind")[random_ind]

  # append classes and priors
  class(samples) <- c(class(samples), "mixed_posteriors.mixture")
  attr(samples, "prior_list") <- prior

  return(samples)
}
.mix_priors.bias <- function(priors, parameter, seed = NULL, n_samples = 10000){

  # check input
  check_list(priors, "priors")
  check_char(parameter, "parameter")
  check_real(seed, "seed", allow_NULL = TRUE)
  check_int(n_samples, "n_samples")

  allowed <- sapply(priors, function(prior){
    is.prior.none(prior) || is.prior.PET(prior) || is.prior.PEESE(prior) ||
      is.prior.weightfunction(prior) || is_prior_phacking(prior) || is_prior_bias(prior)
  })
  if(!all(allowed)){
    stop("'priors' must be a list of publication-bias priors.", call. = FALSE)
  }

  spec        <- selection_backend_spec(priors)
  branch_info <- lapply(priors, .selection_branch_info)

  is_PET       <- sapply(priors, is.prior.PET)
  is_PEESE     <- sapply(priors, is.prior.PEESE)
  has_selection <- vapply(branch_info, function(x) !is.null(x$selection), logical(1))
  has_phacking  <- vapply(branch_info, function(x) !is.null(x$phacking),  logical(1))

  prior_probs <- sapply(priors, .prior_model_weight)
  prior_probs <- prior_probs / sum(prior_probs)

  if(!is.null(seed)){
    set.seed(seed)
  }

  out_names <- character()
  if(any(has_selection)){
    omega_cuts  <- spec$step$breaks
    omega_names <- .weightfunction_omega_names(omega_cuts)
    out_names   <- c(out_names, omega_names)

    selection_priors <- lapply(branch_info[has_selection], function(x) x$selection)
    omega_mapping    <- .weightfunction_mapping_info(selection_priors, one_sided = TRUE)$mapping
    selection_index  <- which(has_selection)
  }
  if(any(has_phacking)){
    phacking_priors <- lapply(branch_info[has_phacking], function(x) x$phacking)
    phacking_names  <- .selection_phacking_report_parameters(phacking_priors)
    out_names <- c(out_names, phacking_names)
  }
  if(any(is_PET)){
    out_names <- c(out_names, "PET")
  }
  if(any(is_PEESE)){
    out_names <- c(out_names, "PEESE")
  }

  samples    <- matrix(nrow = 0, ncol = length(out_names))
  colnames(samples) <- out_names
  sample_ind <- NULL
  models_ind <- NULL

  sample_counts <- .prior_mixture_sample_counts(prior_probs, n_samples)
  for(i in seq_along(priors)[sample_counts > 0]){

    temp_ind <- seq_len(sample_counts[i])
    temp_samples <- matrix(0, nrow = length(temp_ind), ncol = length(out_names))
    colnames(temp_samples) <- out_names

    if(any(has_selection)){
      temp_samples[, omega_names] <- 1
    }

    if(has_selection[i]){
      selection_i <- match(i, selection_index)
      selection_samples <- rng(branch_info[[i]]$selection, length(temp_ind))
      temp_samples[, omega_names] <- selection_samples[, paste0("omega[", omega_mapping[[selection_i]], "]"), drop = FALSE]
    }

    if(has_phacking[i]){
      phacking_samples <- rng(branch_info[[i]]$phacking, length(temp_ind))
      phacking_names <- .phacking_report_parameter(branch_info[[i]]$phacking)
      temp_samples[, phacking_names] <- phacking_samples[, phacking_names, drop = FALSE]
    }

    if(is_PET[i]){
      temp_samples[, "PET"] <- rng(priors[[i]], length(temp_ind), transform_factor_samples = FALSE)
    }
    if(is_PEESE[i]){
      temp_samples[, "PEESE"] <- rng(priors[[i]], length(temp_ind), transform_factor_samples = FALSE)
    }

    samples    <- rbind(samples, temp_samples)
    sample_ind <- c(sample_ind, temp_ind)
    models_ind <- c(models_ind, rep(i, length(temp_ind)))
  }

  samples    <- samples[seq_len(n_samples), , drop = FALSE]
  sample_ind <- sample_ind[seq_len(n_samples)]
  models_ind <- models_ind[seq_len(n_samples)]

  rownames(samples) <- NULL
  attr(samples, "sample_ind") <- sample_ind
  attr(samples, "models_ind") <- models_ind
  attr(samples, "parameter")  <- parameter
  attr(samples, "prior_list") <- priors
  if(any(has_selection)){
    samples <- .weightfunction_set_omega_context(samples, list(
      mapping   = NULL,
      cuts      = omega_cuts,
      names     = omega_names,
      pars      = paste0("omega[", seq_len(length(omega_cuts) - 1L), "]"),
      one_sided = TRUE
    ))
  }
  class(samples) <- c("mixed_posteriors", "mixed_posteriors.bias")

  return(samples)
}

#' @title Compute Savage-Dickey inclusion Bayes factors
#'
#' @description Computes Savage-Dickey (density ratio) inclusion Bayes factors
#' based the change of height from prior to posterior distribution at the test value.
#'
#' @param posterior marginal posterior distribution generated via the
#' \code{marginal_posterior} function
#' @param null_hypothesis point null hypothesis to test. Defaults to \code{0}
#' @param normal_approximation whether the height of prior and posterior density should be
#' approximated via a normal distribution (rather than kernel density). Defaults to \code{FALSE}.
#' @param silent whether warnings should be returned silently. Defaults to \code{FALSE}
#' @param density_method density source for the posterior ordinate. \code{"KDE"}
#' computes a kernel density estimate, using boundary reflection when exact
#' posterior-support metadata is available. \code{"precomputed"} uses a valid
#' \code{posterior_ordinate} attribute when present, then falls back to a valid
#' \code{posterior_density} attribute.
#'
#' @details Marginal posterior vectors may carry a \code{posterior_ordinate}
#' attribute with exact \code{value} and \code{ordinate} entries. When
#' \code{density_method = "precomputed"} and
#' \code{normal_approximation = FALSE}, a matching ordinate is used for the
#' Savage-Dickey ratio. If no matching ordinate is available, a
#' \code{posterior_density} grid with \code{x} and \code{y} coordinates is
#' used before falling back to a kernel density estimate. The fallback KDE uses
#' boundary reflection when exact \code{posterior_support} metadata is attached
#' to the marginal posterior or to a matched posterior-density attribute. Exact
#' support metadata is also checked before accepting precomputed posterior
#' ordinates or densities; support is used to exclude the null only after it
#' is validated against the posterior samples. A stale precomputed value is
#' ignored when compatible exact support excludes the null. Support is not
#' inferred from prior-density grids, posterior-density grids, or plotting
#' ranges, which may be finite numerical integration ranges rather than true
#' support boundaries. Exact support metadata is either a numeric
#' \code{c(lower, upper)} vector or a list with
#' \code{bounds = c(lower, upper)} and \code{exact = TRUE}; optional
#' \code{type = "points"} support is not treated as a continuous interval for
#' KDE boundary reflection. The same schema may be supplied as \code{support}
#' in a \code{posterior_density} attribute. When the prior density at the null
#' is zero or non-finite, the returned Bayes factor carries a warning because
#' the point-null Savage-Dickey ratio is not a regular density ratio at that
#' point.
#'
#' @return \code{Savage_Dickey_BF} returns a Bayes factor.
#'
#' @export
Savage_Dickey_BF <- function(posterior, null_hypothesis = 0, normal_approximation = FALSE, silent = FALSE,
                             density_method = c("KDE", "precomputed")){

  if(!inherits(posterior, "marginal_posterior"))
    stop("'BF_savage_dickey' function requires an object of class 'marginal_posteriors'")
  check_real(null_hypothesis, "null_hypothesis", allow_NA = FALSE)
  if(!is.finite(null_hypothesis)){
    stop("The 'null_hypothesis' argument must be finite.", call. = FALSE)
  }
  check_bool(normal_approximation, "normal_approximation", allow_NA = FALSE)
  check_bool(silent, "silent", allow_NA = FALSE)
  density_method <- .posterior_density_method(density_method)

  if(is.list(posterior)){
    bf <- list()
    for(i in seq_along(posterior)){
      posterior_i <- .posterior_precomputed_child(
        parent          = posterior,
        child           = posterior[[i]],
        index           = i,
        null_hypothesis = null_hypothesis,
        density_method  = density_method
      )
      bf[[i]] <- .Savage_Dickey_BF.fun(posterior_i, null_hypothesis, normal_approximation, silent, density_method)
    }
    names(bf) <- names(posterior)
  }else{
    bf <- .Savage_Dickey_BF.fun(posterior, null_hypothesis, normal_approximation, silent, density_method)
  }

  return(bf)
}

.Savage_Dickey_BF.fun    <- function(posterior, null_hypothesis, normal_approximation, silent, density_method){

  if(is.null(attr(posterior, "prior_density")))
    stop("there are no prior densities for the posterior distribution", call. = FALSE)

  prior <- attr(posterior, "prior_density")

  warnings <- NULL
  stored_posterior_density <- NULL
  stored_posterior_ordinate <- NULL
  posterior_density_source <- if(isTRUE(normal_approximation)) "normal" else "KDE"
  posterior_density_boundary_reflection <- FALSE
  posterior_density_support_bounds <- NULL
  posterior_density_fallback_warnings <- NULL
  BF_error_percent <- NA_real_
  posterior_ordinate_status <- NULL
  posterior_density_status <- NULL
  if(!normal_approximation){
    posterior_ordinate_status <- .posterior_ordinate_direct_status(
      posterior,
      null_hypothesis = null_hypothesis
    )
    posterior_density_status <- .posterior_density_direct_status(posterior)
    if(identical(density_method, "precomputed") &&
       isTRUE(posterior_ordinate_status[["valid"]])){
      stored_posterior_ordinate <- posterior_ordinate_status[["value"]]
    }
    if(identical(density_method, "precomputed") &&
       isTRUE(posterior_density_status[["valid"]])){
      stored_posterior_density <- posterior_density_status[["value"]]
    }
  }
  stored_posterior_density_support <- if(!is.null(stored_posterior_density)){
    stored_posterior_density[["support"]]
  }else{
    NULL
  }
  if(identical(density_method, "precomputed") &&
     is.null(stored_posterior_ordinate) &&
     is.null(stored_posterior_density)){
    if(!is.null(posterior_ordinate_status) &&
       isTRUE(posterior_ordinate_status[["present"]]) &&
       isTRUE(posterior_ordinate_status[["relevant"]]) &&
       !isTRUE(posterior_ordinate_status[["valid"]])){
      fallback_warning <- paste0(
        "Precomputed posterior ordinate metadata is present but invalid ",
        "for the requested null hypothesis. Falling back to the kernel ",
        "density estimate."
      )
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(
        posterior_density_fallback_warnings,
        fallback_warning
      )
    }
    if(!is.null(posterior_density_status) &&
       isTRUE(posterior_density_status[["present"]]) &&
       isTRUE(posterior_density_status[["relevant"]]) &&
       !isTRUE(posterior_density_status[["valid"]])){
      fallback_warning <- paste0(
        "Precomputed posterior density metadata is present but invalid. ",
        "Falling back to the kernel density estimate."
      )
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(
        posterior_density_fallback_warnings,
        fallback_warning
      )
    }
  }

  if(mean(posterior == null_hypothesis) > 0.05){
    stop(
      "There is a considerable cluster of posterior samples at the exact null hypothesis value. The Savage-Dickey density ratio is invalid.",
      call. = FALSE
    )
  }
  if(!is.null(stored_posterior_density) && nrow(stored_posterior_density[["point_masses"]]) > 0L){
    point_masses <- stored_posterior_density[["point_masses"]]
    point_tol <- sqrt(.Machine$double.eps) * max(1, abs(null_hypothesis))
    null_point_mass <- sum(point_masses[["mass"]][abs(point_masses[["x"]] - null_hypothesis) <= point_tol])
    if(null_point_mass > 0){
      stop(
        "Stored posterior density contains a point mass at the exact null hypothesis value. The Savage-Dickey density ratio is invalid.",
        call. = FALSE
      )
    }
  }
  if(.prior_linear_density_point_mass(prior, null_hypothesis) > 0){
    stop(
      "There is a point mass in the prior at the exact null hypothesis value. The Savage-Dickey density ratio is invalid.",
      call. = FALSE
    )
  }

  prior_range <- range(c(
    if(!is.null(prior$density)) prior$density$x else NULL,
    if(!is.null(prior$points) && nrow(prior$points) > 0) prior$points$x else NULL
  ))
  if(null_hypothesis < prior_range[1] || null_hypothesis > prior_range[2]){
    warnings <- c(warnings, "Prior density does not span both sides of the null hypothesis. Check whether the prior distribution contains the null hypothesis in the first place. The Savage-Dickey density ratio is likely to be invalid.")
  }
  posterior_range <- range(posterior)
  posterior_support_bounds <- .posterior_support_bounds(
    posterior,
    interval_only = TRUE
  )
  if(is.null(posterior_support_bounds)){
    stored_support <- .posterior_support_from_attribute(stored_posterior_density_support)
    if(!is.null(stored_support) && isTRUE(stored_support$exact) &&
       .posterior_support_has_interval(stored_support)){
      posterior_support_bounds <- stored_support$bounds
    }
  }
  null_at_support_boundary <- FALSE
  if(!is.null(posterior_support_bounds)){
    boundary_tol <- sqrt(.Machine$double.eps) * max(1, abs(null_hypothesis), abs(posterior_support_bounds[is.finite(posterior_support_bounds)]))
    null_at_support_boundary <- any(is.finite(posterior_support_bounds) & abs(null_hypothesis - posterior_support_bounds) <= boundary_tol)
  }
  if(!is.null(stored_posterior_density) && is.null(stored_posterior_ordinate)){
    posterior_range <- range(stored_posterior_density[["x"]], finite = TRUE)
    if(null_hypothesis < posterior_range[1] || null_hypothesis > posterior_range[2]){
      fallback_warning <- "Stored posterior density does not span both sides of the null hypothesis. Falling back to the kernel density estimate."
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(posterior_density_fallback_warnings, fallback_warning)
      stored_posterior_density <- NULL
      posterior_range <- range(posterior)
    }
  }
  if(is.null(stored_posterior_ordinate) &&
     (null_hypothesis < posterior_range[1] || null_hypothesis > posterior_range[2]) &&
     !isTRUE(null_at_support_boundary)){
    warnings <- c(warnings, "Posterior samples do not span both sides of the null hypothesis. The Savage-Dickey density ratio is likely to be overestimated.")
  }

  kde_height <- function(support = NULL){
    height <- .Savage_Dickey_BF.kd(
      samples         = posterior,
      null_hypothesis = null_hypothesis,
      support         = support
    )
    support_warning <- attr(height, "posterior_support_warning", exact = TRUE)
    if(!is.null(support_warning)){
      warnings <<- c(warnings, support_warning)
    }
    if(isTRUE(attr(height, "boundary_reflection", exact = TRUE))){
      posterior_density_boundary_reflection <<- TRUE
    }
    support_bounds <- attr(height, "posterior_support_bounds", exact = TRUE)
    if(!is.null(support_bounds)){
      posterior_density_support_bounds <<- support_bounds
    }
    height
  }

  if(normal_approximation){
    posterior_height <- .Savage_Dickey_BF.normal(posterior, null_hypothesis)
  }else if(!is.null(stored_posterior_ordinate)){
    support_exclusion <- .Savage_Dickey_BF.support_exclusion(
      posterior,
      null_hypothesis = null_hypothesis,
      source_support  = stored_posterior_density_support
    )
    warnings <- c(warnings, support_exclusion[["warnings"]])
    if(isTRUE(support_exclusion[["excluded"]])){
      fallback_warning <- "Exact posterior support excludes the null hypothesis. Ignoring the precomputed posterior ordinate."
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(posterior_density_fallback_warnings, fallback_warning)
      posterior_height <- 0
      posterior_density_support_bounds <- support_exclusion[["bounds"]]
    }else{
      posterior_height <- stored_posterior_ordinate[["y"]]
      posterior_density_source <- "precomputed"
      BF_error_percent <- .posterior_ordinate_bf_error_percent(stored_posterior_ordinate)
    }
  }else if(!is.null(stored_posterior_density)){
    support_exclusion <- .Savage_Dickey_BF.support_exclusion(
      posterior,
      null_hypothesis = null_hypothesis,
      source_support  = stored_posterior_density[["support"]]
    )
    warnings <- c(warnings, support_exclusion[["warnings"]])
    if(isTRUE(support_exclusion[["excluded"]])){
      fallback_warning <- "Exact posterior support excludes the null hypothesis. Ignoring the precomputed posterior density."
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(posterior_density_fallback_warnings, fallback_warning)
      posterior_height <- 0
      posterior_density_support_bounds <- support_exclusion[["bounds"]]
    }else{
      posterior_height <- .posterior_density_height(stored_posterior_density, null_hypothesis)
    }
    if(!isTRUE(support_exclusion[["excluded"]]) &&
       (!is.finite(posterior_height) || posterior_height <= 0)){
      fallback_warning <- "Stored posterior density has zero or non-finite height at the null hypothesis. Falling back to the kernel density estimate."
      warnings <- c(warnings, fallback_warning)
      posterior_density_fallback_warnings <- c(posterior_density_fallback_warnings, fallback_warning)
      posterior_height <- kde_height(stored_posterior_density[["support"]])
    }else if(!isTRUE(support_exclusion[["excluded"]])){
      posterior_density_source <- "precomputed"
      BF_error_percent <- .posterior_density_bf_error_percent(stored_posterior_density, null_hypothesis)
    }
  }else{
    posterior_height <- kde_height(stored_posterior_density_support)
  }
  prior_height <- .prior_linear_density_height(prior, null_hypothesis)
  if(!is.finite(prior_height) || prior_height <= 0){
    warnings <- c(
      warnings,
      "Prior density at the null hypothesis value is zero or non-finite. The Savage-Dickey density ratio is invalid."
    )
  }

  if(!silent && !is.null(warnings)){
    sapply(warnings, warning, call. = FALSE)
  }

  BF <- exp(log(prior_height) - log(posterior_height))

  if(!is.null(warnings)){
    attr(BF, "warnings") <- warnings
  }
  if(is.finite(BF_error_percent)){
    attr(BF, "BF_error_percent") <- BF_error_percent
  }
  attr(BF, "posterior_density_source") <- posterior_density_source
  if(isTRUE(posterior_density_boundary_reflection)){
    attr(BF, "posterior_density_boundary_reflection") <- TRUE
  }
  if(!is.null(posterior_density_support_bounds)){
    attr(BF, "posterior_density_support") <- posterior_density_support_bounds
  }
  if(length(posterior_density_fallback_warnings) > 0L){
    attr(BF, "posterior_density_fallback") <- TRUE
    attr(BF, "posterior_density_fallback_warnings") <- posterior_density_fallback_warnings
  }

  return(BF)
}
.Savage_Dickey_BF.normal <- function(samples, null_hypothesis){

  height <- stats::dnorm(null_hypothesis, mean = mean(samples), sd = stats::sd(samples))

  return(height)
}

.Savage_Dickey_BF.support_exclusion <- function(samples, null_hypothesis,
                                                source_support = NULL){

  supports <- list(source_support, .posterior_support_get(samples))
  valid_bounds <- NULL
  support_warnings <- NULL

  for(support in supports){
    support <- .posterior_support_from_attribute(support)
    if(is.null(support) || !isTRUE(support$exact)){
      next
    }

    support_info <- .posterior_support_for_kde(samples, support = support)
    if(!is.null(support_info[["warning"]])){
      support_warnings <- c(support_warnings, support_info[["warning"]])
    }
    if(is.null(support_info[["bounds"]])){
      next
    }
    if(is.null(valid_bounds)){
      valid_bounds <- support_info[["bounds"]]
    }

    if(.posterior_support_excludes_value(
      .posterior_support_new(support_info[["bounds"]]),
      null_hypothesis
    )){
      return(list(
        excluded = TRUE,
        bounds   = support_info[["bounds"]],
        warnings = support_warnings
      ))
    }
  }

  list(excluded = FALSE, bounds = valid_bounds, warnings = support_warnings)
}

.Savage_Dickey_BF.kd     <- function(samples, null_hypothesis, support = NULL){

  sample_values <- as.numeric(samples)
  sample_values <- sample_values[is.finite(sample_values)]
  support_info <- .posterior_support_for_kde(samples, support = support)
  support_bounds <- support_info[["bounds"]]

  if(!is.null(support_bounds)){
    if(null_hypothesis < support_bounds[1] || null_hypothesis > support_bounds[2]){
      height <- 0
      attr(height, "posterior_support_bounds") <- support_bounds
      return(height)
    }

    if(any(is.finite(support_bounds))){
      density_args <- list(
        x      = sample_values,
        n      = 512L,
        bounds = support_bounds,
        na.rm  = TRUE
      )
      if(is.finite(support_bounds[1])){
        density_args[["from"]] <- support_bounds[1]
      }
      if(is.finite(support_bounds[2])){
        density_args[["to"]] <- support_bounds[2]
      }
      density_posterior <- do.call(.density_kde_boundary, density_args)
      height <- stats::approx(
        density_posterior$x,
        density_posterior$y,
        xout  = null_hypothesis,
        yleft = 0,
        yright = 0
      )[["y"]]
      attr(height, "boundary_reflection") <- isTRUE(attr(density_posterior, "boundary_reflection"))
      attr(height, "posterior_support_bounds") <- support_bounds
      return(height)
    }
  }

  if(null_hypothesis < min(sample_values) || null_hypothesis > max(sample_values)){
    height <- 0
  }else{
    density_posterior <- stats::density(sample_values)
    height <- stats::approx(
      density_posterior$x,
      density_posterior$y,
      xout   = null_hypothesis,
      yleft  = 0,
      yright = 0
    )[["y"]]
  }

  if(!is.null(support_info[["warning"]])){
    attr(height, "posterior_support_warning") <- support_info[["warning"]]
  }

  return(height)
}


#' @title Model-average marginal posterior distributions and
#' marginal Bayes factors
#'
#' @description Creates marginal model-averaged and conditional
#' posterior distributions based on a list of models, vector of parameters,
#' formula, and a list of indicators of the null or alternative hypothesis models
#' for each parameter. Computes inclusion Bayes factors for each
#' marginal estimate via a Savage-Dickey density approximation.
#'
#' @param marginal_parameters parameters for which the the marginal summary
#' should be created
#' @param parameters all parameters included in the model_list that are
#' relevant for the formula (all of which need to have specification of
#' \code{is_null_list})
#' @param seed seed for random number generation
#' @param density_method posterior density method used for Savage-Dickey Bayes
#' factors. Currently only \code{"KDE"} is supported by
#' \code{marginal_inference()} and \code{as_marginal_inference()} because
#' generic model-averaged marginal posteriors do not have a well-defined
#' precomputed density source.
#' @inheritParams ensemble_inference
#' @inheritParams marginal_posterior
#' @inheritParams Savage_Dickey_BF
#'
#' @return \code{marginal_inference} returns an object of class 'marginal_inference'.
#'
#' @seealso [ensemble_inference] [mix_posteriors] [BayesTools_ensemble_tables]
#'
#' @export
marginal_inference <- function(model_list, marginal_parameters, parameters, is_null_list, formula,
                               null_hypothesis = 0, normal_approximation = FALSE,
                               n_samples = 10000, seed = NULL, silent = FALSE,
                               density_method = "KDE"){

  # check input (majority of the checks performed within mix_posteriors)
  check_list(model_list, "model_list")
  check_char(parameters, "parameters", check_length = FALSE)
  check_char(marginal_parameters, "marginal_parameters", check_length = FALSE)
  check_list(is_null_list, "is_null_list", check_length = length(parameters))
  if(!all(unlist(sapply(model_list, function(m) sapply(attr(m[["fit"]], "prior_list"), function(p) is.prior(p))))))
    stop("model_list:priors must contain 'BayesTools' priors")
  density_method <- .marginal_inference_density_method(density_method)


  # create one full model-averaged ensemble
  averaged_posterior <- mix_posteriors(
    model_list   = model_list,
    parameters   = parameters,
    is_null_list = is_null_list,
    seed         = seed,
    n_samples    = n_samples,
    conditional  = FALSE
  )

  # prepare output object
  out <- list(
    conditional = list(),
    averaged    = list(),
    inference   = list()
  )

  for(i in seq_along(marginal_parameters)){

    if(all(is_null_list[[marginal_parameters[i]]])){
      warning(paste0("parameter '", marginal_parameters[i], "' does not contain any alternative hypothesis models."), immediate. = TRUE, call. = FALSE)
      next
    }

    # obtain model-averaged posterior conditional on including the parameter of interest
    # (different from individual conditionals)
    temp_conditional_posterior <- mix_posteriors(
      model_list   = model_list[!is_null_list[[marginal_parameters[i]]]],
      parameters   = parameters,
      is_null_list = lapply(is_null_list, function(l) l[!is_null_list[[marginal_parameters[i]]]]),
      seed         = seed,
      n_samples    = n_samples,
      conditional  = FALSE
    )

    # compute the marginals
    out[["averaged"]][[marginal_parameters[i]]] <- marginal_posterior(
      samples           = averaged_posterior,
      parameter         = marginal_parameters[i],
      formula           = formula,
      prior_samples     = TRUE,
      n_samples         = n_samples
    )
    out[["conditional"]][[marginal_parameters[i]]] <- marginal_posterior(
      samples           = temp_conditional_posterior,
      parameter         = marginal_parameters[i],
      formula           = formula,
      prior_samples     = TRUE,
      n_samples         = n_samples
    )

    # and inclusion Bayes factor
    out[["inference"]][[marginal_parameters[i]]] <- Savage_Dickey_BF(
      posterior            = out[["conditional"]][[marginal_parameters[i]]],
      null_hypothesis      = null_hypothesis,
      normal_approximation = normal_approximation,
      silent               = silent,
      density_method       = density_method
    )
  }

  attr(out, "null_hypothesis")      <- null_hypothesis
  attr(out, "normal_approximation") <- normal_approximation
  attr(out, "density_method")        <- density_method
  class(out) <- c(class(out), "marginal_inference")
  return(out)
}


#' @title Model-average marginal posterior distributions and
#' marginal Bayes factors based on BayesTools JAGS model via \code{marginal_inference}
#'
#' @description Creates marginal model-averaged and conditional
#' posterior distributions based on a BayesTools JAGS model, vector of parameters,
#' formula, and a list of conditional specifications for each parameter.
#' Computes inclusion Bayes factors for each marginal estimate via a Savage-Dickey
#' density approximation.
#'
#' @param marginal_parameters parameters for which the the marginal summary
#' should be created
#' @param conditional_list list of conditional parameters for each marginal parameter
#' @param parameters all parameters included in the model_list that are
#' relevant for the formula (all of which need to have specification of
#' \code{is_null_list})
#' @inheritParams as_mixed_posteriors
#' @inheritParams marginal_inference
#' @inheritParams Savage_Dickey_BF
#'
#' @return \code{as_marginal_inference} returns an object of class 'marginal_inference'.
#'
#' @seealso [marginal_inference] [as_mixed_posteriors]
#'
#' @export
as_marginal_inference <- function(model, marginal_parameters, parameters, conditional_list, conditional_rule, formula,
                                  null_hypothesis = 0, normal_approximation = FALSE,
                                  n_samples = 10000, silent = FALSE, force_plots = FALSE,
                                  density_method = "KDE"){

  # check input (majority of the checks performed within mix_posteriors)
  # check input
  if(!inherits(model, "BayesTools_fit"))
    stop("'model' must be a 'BayesTools_fit'")
  check_char(parameters, "parameters", check_length = FALSE)
  check_char(marginal_parameters, "marginal_parameters", check_length = FALSE)
  check_list(conditional_list, "conditional_list", check_length = length(marginal_parameters))
  check_char(conditional_rule, "conditional_rule")
  density_method <- .marginal_inference_density_method(density_method)

  priors <- attr(model, "prior_list")


  # create one full model-averaged ensemble
  averaged_posterior <- as_mixed_posteriors(
    model        = model,
    parameters   = parameters
  )

  # prepare output object
  out <- list(
    conditional = list(),
    averaged    = list(),
    inference   = list()
  )

  for(i in seq_along(marginal_parameters)){

    check_char(
      conditional_list[[marginal_parameters[i]]],
      sprintf("conditional_list[[%1$s]]", marginal_parameters[i]),
      check_length = FALSE,
      allow_values = c(parameters, "PET", "PEESE", "PETPEESE", "omega", "phacking", "alpha", "pi_null"),
      allow_NULL = TRUE
    )

    # compute the marginals
    out[["averaged"]][[marginal_parameters[i]]] <- marginal_posterior(
      samples           = averaged_posterior,
      parameter         = marginal_parameters[i],
      formula           = formula,
      prior_samples     = TRUE,
      n_samples         = n_samples
    )

    out[["conditional"]][[marginal_parameters[i]]] <- .marginal_inference_conditional_posterior(
      model              = model,
      parameters         = parameters,
      marginal_parameter = marginal_parameters[i],
      formula            = formula,
      averaged_marginal  = out[["averaged"]][[marginal_parameters[i]]],
      prior_list         = attr(averaged_posterior, "prior_list"),
      conditional        = conditional_list[[marginal_parameters[i]]],
      conditional_rule   = conditional_rule,
      n_samples          = n_samples,
      force_plots        = force_plots
    )

    if(length(out[["conditional"]][[marginal_parameters[i]]]) == 0){
      out[["averaged"]][[marginal_parameters[i]]] <- NULL
      next
    }

    # and inclusion Bayes factor
    out[["inference"]][[marginal_parameters[i]]] <- Savage_Dickey_BF(
      posterior            = out[["conditional"]][[marginal_parameters[i]]],
      null_hypothesis      = null_hypothesis,
      normal_approximation = normal_approximation,
      silent               = silent,
      density_method       = density_method
    )
  }

  attr(out, "null_hypothesis")      <- null_hypothesis
  attr(out, "normal_approximation") <- normal_approximation
  attr(out, "density_method")        <- density_method
  class(out) <- c(class(out), "marginal_inference")
  return(out)
}

.marginal_inference_density_method <- function(density_method){

  density_method <- .posterior_density_method(density_method)
  if(identical(density_method, "precomputed")){
    stop(
      "'density_method = \"precomputed\"' is not supported by ",
      "'marginal_inference()' or 'as_marginal_inference()'. ",
      "Precomputed densities must be computed for the marginal posterior ",
      "itself and passed directly to 'Savage_Dickey_BF()'.",
      call. = FALSE
    )
  }

  return(density_method)
}

.marginal_inference_condition_key <- function(conditional, conditional_rule = "AND"){

  .condition_event_key(conditional, conditional_rule)
}

.marginal_inference_level_conditionals <- function(marginal, prior_list, conditional,
                                                   conditional_rule = "AND"){

  levels <- names(marginal)
  conditionals <- lapply(levels, function(level){
    weights <- attr(marginal[[level]], "linear_weights")
    if(is.null(weights)){
      return(conditional)
    }
    if(!is.null(dim(weights))){
      row_conditionals <- lapply(seq_len(nrow(weights)), function(row_i){
        .prior_linear_active_conditionals(
          prior_list  = prior_list,
          weights     = weights[row_i, ],
          conditional = conditional
        )
      })
      row_keys <- vapply(row_conditionals, .condition_labels_key, character(1))
      if(length(unique(row_keys)) > 1L){
        stop(
          "Row-varying active conditional sets are not supported for marginal inference.",
          call. = FALSE
        )
      }
      return(row_conditionals[[1]])
    }
    .prior_linear_active_conditionals(
      prior_list   = prior_list,
      weights      = weights,
      conditional  = conditional
    )
  })
  names(conditionals) <- levels

  conditionals
}

.marginal_inference_conditional_posterior <- function(model, parameters, marginal_parameter,
                                                      formula, averaged_marginal, prior_list,
                                                      conditional, conditional_rule, n_samples,
                                                      force_plots){

  level_conditionals <- .marginal_inference_level_conditionals(
    marginal    = averaged_marginal,
    prior_list  = prior_list,
    conditional = conditional,
    conditional_rule = conditional_rule
  )

  conditional_marginal <- averaged_marginal
  marginal_cache <- list()

  for(level in names(level_conditionals)){
    level_conditional <- level_conditionals[[level]]
    level_event <- .condition_event(
      prior_list        = prior_list,
      conditional       = level_conditional,
      conditional_rule  = conditional_rule
    )
    key <- level_event[["condition_key"]]

    if(is.null(marginal_cache[[key]])){
      conditional_posterior <- as_mixed_posteriors(
        model            = model,
        parameters       = parameters,
        conditional      = if(length(level_conditional) == 0) NULL else level_conditional,
        conditional_rule = conditional_rule,
        force_plots      = force_plots
      )

      if(length(conditional_posterior) == 0){
        return(list())
      }else{
        marginal_cache[[key]] <- marginal_posterior(
          samples       = conditional_posterior,
          parameter     = marginal_parameter,
          formula       = formula,
          prior_samples = TRUE,
          n_samples     = n_samples
        )
      }
    }

    if(length(marginal_cache[[key]]) == 0){
      return(list())
    }

    conditional_marginal[[level]] <- marginal_cache[[key]][[level]]
    conditional_marginal[[level]] <- .condition_event_set_attributes(
      conditional_marginal[[level]],
      level_event,
      effective = TRUE
    )
  }

  conditional_marginal
}

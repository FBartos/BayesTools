#' @rdname BayesTools_ensemble_tables
marginal_estimates_table <- function(samples, inference, parameters, probs = c(0.025, 0.5, 0.975), logBF = FALSE, BF01 = FALSE, title = NULL, footnotes = NULL, warnings = NULL, formula_prefix = TRUE, transform_scaled = FALSE, formula_scale = NULL){

  # check input
  check_char(parameters, "parameters", check_length = 0)
  check_list(samples, "samples", check_names = parameters, all_objects = TRUE, allow_other = TRUE)
  check_list(inference, "inference", check_names = parameters, all_objects = TRUE, allow_other = TRUE)
  check_real(probs, "probs", lower = 0, upper = 1, check_length = 0, allow_NULL = TRUE)
  check_bool(logBF, "logBF", allow_NA = FALSE)
  check_bool(BF01,  "BF01",  allow_NA = FALSE)
  check_char(title, "title", allow_NULL = TRUE)
  check_char(footnotes, "footnotes", check_length = 0, allow_NULL = TRUE)
  check_char(warnings, "warnings", check_length = 0, allow_NULL = TRUE)
  check_bool(formula_prefix, "formula_prefix")
  check_bool(transform_scaled, "transform_scaled")
  check_list(formula_scale, "formula_scale", allow_NULL = TRUE)

  # transform scaled coefficients back to original scale
  if(transform_scaled && !is.null(formula_scale) && length(formula_scale) > 0){
    samples <- .transform_scale_samples_list(samples, formula_scale)
  }


  # extract values
  estimates_table <- NULL
  row_parts <- list()
  row_quantity_ids <- character()
  row_log_BF <- numeric()
  row_diagnostics <- list()
  for(parameter in parameters){

    # the label parts of every level: rows and warnings are rendered from them
    level_parts  <- .bt_marginal_level_parts(samples[[parameter]], parameter)
    level_labels <- .bt_label(level_parts, style = "table", formula_prefix = formula_prefix)
    row_parts <- c(row_parts, level_parts)
    row_quantity_ids <- c(row_quantity_ids, .bt_marginal_level_quantity_ids(samples[[parameter]]))
    level_warning_labels <- .bt_label(level_parts, style = "warning", formula_prefix = formula_prefix)

    # extract the relevant information
    if(is.list(samples[[parameter]]) && length(samples[[parameter]]) > 1){
      temp_samples  <- .marginal_posterior_parameter_samples(samples, parameter)
      temp_BF       <- do.call(c, inference[[parameter]])
      temp_BF_error <- .marginal_inference_BF_error_percent(inference[[parameter]], temp_BF)
      # the warnings of each level are keyed by that level
      warning_levels <- if(!is.null(names(inference[[parameter]])) &&
                           !is.null(names(samples[[parameter]]))){
        match(names(inference[[parameter]]), names(samples[[parameter]]))
      }else{
        seq_along(inference[[parameter]])
      }
      temp_warnings <- do.call(c, lapply(seq_along(inference[[parameter]]), function(lvl) {
        if(is.null(attr(inference[[parameter]][[lvl]], "warnings"))){
          return()
        }else{
          paste0(level_warning_labels[[warning_levels[[lvl]]]], ": ", attr(inference[[parameter]][[lvl]], "warnings"))
        }
      }))
    }else{
      temp_samples  <- .marginal_posterior_parameter_samples(samples, parameter)
      # a scalar Savage-Dickey BF keeps its attributes only when not subset
      temp_BF       <- if(is.list(inference[[parameter]])) inference[[parameter]][[1]] else inference[[parameter]]
      temp_BF_error <- .marginal_inference_BF_error_percent(inference[[parameter]], temp_BF)
      if(is.null(attr(temp_BF, "warnings"))){
        temp_warnings <- NULL
      }else{
        temp_warnings <- paste0(level_warning_labels[[1L]], ": ", attr(temp_BF, "warnings"))
      }
    }

    producers <- if(is.list(samples[[parameter]]) && length(samples[[parameter]]) > 1L){
      inference[[parameter]]
    }else list(temp_BF)
    row_log_BF <- c(row_log_BF, vapply(producers, function(value){
      logs <- .BF_carrier_log(value)
      if(is.null(logs)) log(as.numeric(value)) else logs
    }, numeric(1)))
    row_diagnostics <- c(row_diagnostics, lapply(producers, function(value) attr(value, "numerical_diagnostics")))
    # add estimates
    par_summary <- cbind(
      "Mean" = vapply(temp_samples, mean, numeric(1)),
      "SD"   = vapply(temp_samples, stats::sd, numeric(1))
    )
    for(i in seq_along(probs)){
      par_summary <- cbind(par_summary, vapply(temp_samples, stats::quantile, numeric(1), probs = probs[i]))
      colnames(par_summary)[ncol(par_summary)] <- probs[i]
    }

    # add BF
    par_summary <- cbind(
      par_summary,
      "inclusion_BF"     = temp_BF,
      "BF_error_percent" = temp_BF_error
    )


    rownames(par_summary) <- level_labels
    estimates_table       <- rbind(estimates_table, par_summary)

    # add warnings
    if(!is.null(temp_warnings)){
      warnings <- c(warnings, temp_warnings)
    }
  }

  # prepare output
  estimates_table                    <- data.frame(estimates_table, check.names = FALSE)
  has_BF_error                       <- any(is.finite(estimates_table[["BF_error_percent"]]))
  if(!has_BF_error){
    estimates_table[["BF_error_percent"]] <- NULL
  }
  estimates_table[["inclusion_BF"]] <- .format_BF_from_log(row_log_BF,
    logBF = logBF, BF01 = BF01, inclusion = TRUE,
    BF = estimates_table[["inclusion_BF"]], diagnostics = row_diagnostics)
  attr(estimates_table, "raw_log_BF") <- row_log_BF
  attr(estimates_table, "numerical_diagnostics") <- row_diagnostics
  if(has_BF_error){
    attr(estimates_table[["BF_error_percent"]], "name") <- .BF_error_column_name(BF01)
  }
  class(estimates_table)             <- c("BayesTools_table", "BayesTools_marginal_estimates", class(estimates_table))
  table_type                         <- rep("estimate", ncol(estimates_table))
  table_type[colnames(estimates_table) == "inclusion_BF"] <- "inclusion_BF"
  table_type[colnames(estimates_table) == "BF_error_percent"] <- "BF_error"
  attr(estimates_table, "type")      <- table_type
  attr(estimates_table, "quantities") <- .bt_table_quantities(
    rows         = rownames(estimates_table),
    label_parts  = row_parts,
    quantity_ids = row_quantity_ids
  )
  attr(estimates_table, "rownames")  <- TRUE
  attr(estimates_table, "title")     <- title
  attr(estimates_table, "footnotes") <- footnotes
  attr(estimates_table, "warnings")  <- warnings

  return(estimates_table)
}

# The quantity ids the levels of a marginal posterior declare ("" for levels
# without a column table, and for estimated marginal means).
.bt_marginal_level_quantity_ids <- function(x){

  levels <- if(is.list(x) && !is.numeric(x)) x else list(x)
  vapply(levels, function(level){
    quantities <- .bt_draws_quantities(level)
    if(is.null(quantities)) "" else quantities$quantity_id[[1L]]
  }, character(1), USE.NAMES = FALSE)
}

.marginal_inference_BF_error_percent <- function(inference, BF){

  out <- rep(NA_real_, length(BF))
  names(out) <- names(BF)
  if(length(out) == 0L){
    return(out)
  }

  if(is.list(inference) && !inherits(inference, "marginal_inference")){
    errors <- vapply(inference, .BF_error_percent_value, numeric(1))
    if(length(errors) == length(out)){
      out <- errors
      names(out) <- names(BF)
    }else if(!is.null(names(out)) && !is.null(names(errors))){
      out[] <- errors[names(out)]
    }
  }else{
    if(is.list(inference)){
      out[] <- .BF_error_percent_value(inference[[1]])
    }else{
      out[] <- .BF_error_percent_value(inference)
    }
  }

  return(out)
}

.BF_error_percent_value <- function(x){

  BF_error_percent <- attr(x, "BF_error_percent")
  if(is.null(BF_error_percent)){
    return(NA_real_)
  }

  BF_error_percent <- as.numeric(BF_error_percent)[1]
  if(!is.finite(BF_error_percent) || BF_error_percent < 0){
    return(NA_real_)
  }

  return(BF_error_percent)
}



.ensemble_table_foundation <- function(models, parameters, remove_spike_0, short_name){

  model_rows <- list()
  for(i in seq_along(models)){

    model_row <- list()
    model_row[["Model"]] <- models[[i]][["inference"]][["m_number"]]

    temp_prior_list <- attr(models[[i]][["fit"]], "prior_list")

    for(p in seq_along(parameters)){
      if(is.list(parameters)){
        if(sum(names(temp_prior_list) %in% parameters[[p]]) == 1){
          temp_prior <- temp_prior_list[[parameters[[p]][parameters[[p]] %in% names(temp_prior_list)]]]
        }else if(sum(names(temp_prior_list) %in% parameters[[p]]) == 0){
          temp_prior <- prior_none()
        }else{
          stop("More than one prior matching the specified grouping.")
        }
      }else{
        if(any(names(temp_prior_list) == parameters[p])){
          temp_prior <- temp_prior_list[[parameters[p]]]
        }else{
          temp_prior <- prior_none()
        }
      }
      if(remove_spike_0 && is.prior.point(temp_prior) && temp_prior[["parameters"]][["location"]] == 0){
        model_row[[names(parameters)[p]]] <- ""
      }else if(is.prior.none(temp_prior)){
        model_row[[names(parameters)[p]]] <- ""
      }else{
        model_row[[names(parameters)[p]]] <- print(temp_prior, silent = TRUE, short_name = short_name)
      }
    }
    model_rows[[i]] <- model_row
  }

  summary_table <- data.frame(do.call(rbind, model_rows))
  for(i in 1:ncol(summary_table)){
    summary_table[,i] <- unlist(summary_table[,i])
  }

  colnames(summary_table) <- c("Model", names(parameters))

  # formula parameters are labelled by their term, rendered from the prior
  parameters <- unlist(parameters) # deal with potential matching of multiple parameters withing a name
  for(p in seq_along(parameters)){

    priors <- lapply(models, function(m) attr(m[["fit"]], "prior_list")[[parameters[p]]])
    priors <- priors[!vapply(priors, is.null, logical(1))]
    if(length(priors) == 0L || !nzchar(.bt_label_formula_parameter(priors[[1L]]))){
      next
    }
    colnames(summary_table)[colnames(summary_table) == parameters[p]] <- .bt_label(
      .bt_label_parts_term(parameters[p], priors[[1L]]),
      style = "table"
    )
  }

  return(summary_table)
}
.fit_summary_column <- function(fit_summary, column){

  if(is.null(fit_summary) || !column %in% colnames(fit_summary)){
    return(NA_real_)
  }

  fit_summary[, column]
}
.max_or_na <- function(x){

  if(length(x) == 0 || all(is.na(x))){
    return(NA_real_)
  }

  max(x, na.rm = TRUE)
}
.min_or_na <- function(x){

  if(length(x) == 0 || all(is.na(x))){
    return(NA_real_)
  }

  min(x, na.rm = TRUE)
}
